"""Record the installed dependency closure after an explicit dependency upgrade."""
from importlib.metadata import distribution
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def closure(roots):
    found = {}
    pending = list(roots)
    while pending:
        name = canonicalize_name(pending.pop())
        if name in found:
            continue
        dist = distribution(name)
        found[name] = dist.version
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker is None or req.marker.evaluate():
                pending.append(req.name)
    return '\n'.join(f'{name}=={version}' for name, version in sorted(found.items())) + '\n'


if __name__ == '__main__':
    for filename, roots in [('requirements-docs.txt', ['zensical']),
                            ('requirements-docs-browser.txt', ['playwright']),
                            ('requirements-test.txt', ['pytest', 'pyecore', 'lxml'])]:
        Path(filename).write_text('# Validated on Python 3.14; generated by scripts/lock_docs.py\n' + closure(roots))
